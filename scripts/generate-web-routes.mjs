#!/usr/bin/env node
/**
 * Write each application's route entry files from the shared route manifest.
 *
 * Next resolves routes from the filesystem, so a screen in `@aflow/web-product`
 * only becomes a route once a file exists at the right path in an application.
 * Those files differ only in the screen they name, and hand-writing them per
 * application is two route trees to keep in step — which is what the manifest
 * replaces.
 *
 * Generated output is committed and compared, the same way the background-work
 * docs are: the tree is visible in review and to an editor, and `--check` fails
 * when it drifts from the table.
 *
 * Usage: node scripts/generate-web-routes.mjs [--check]
 */
import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  rmdirSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = dirname(dirname(fileURLToPath(import.meta.url)));
const CHECK = process.argv.includes('--check');

/**
 * Which editions each application serves, which is not the same as which edition
 * it is named after.
 *
 * Each serves one edition now. The appliance runs `apps/web-local`, and so does
 * `yarn dev:local`, so nothing reaches the local edition through `apps/web` any
 * more — and a route only the local edition serves is absent from it rather than
 * present and gated at render time.
 *
 * That is the boundary in the form the plan asks for: a property of what ships
 * rather than of what runs. `s/[space]/computer` is the first route it removes —
 * a paired machine is something only an operator running the appliance has.
 */
const APPS = {
  'apps/web': {
    dir: join(REPO, 'apps/web/src/app/(dashboard)'),
    serves: ['hosted'],
  },
  'apps/web-local': {
    dir: join(REPO, 'apps/web-local/src/app/(dashboard)'),
    serves: ['local'],
  },
};

const BANNER =
  '// Generated by scripts/generate-web-routes.mjs — edit the manifest, not this file.';

/** Read the manifest from source, so generating needs no build. */
function readManifest() {
  const src = readFileSync(join(REPO, 'packages/web-product/src/ui/routeManifest.ts'), 'utf8');
  const body = src.slice(src.indexOf('ROUTE_MANIFEST'));
  const entries = [];
  // Each `{ … }` in the table, then field by field — a single pattern spanning
  // the whole entry has to be rewritten every time one gains a field, and fails
  // silently by matching nothing when it is not.
  for (const block of body.matchAll(/\{[^{}]*route:[^{}]*\}/g)) {
    const text = block[0];
    const route = /route:\s*'([^']+)'/.exec(text)?.[1];
    const screen = /screen:\s*'([^']+)'/.exec(text)?.[1];
    const editionsRaw = /editions:\s*(BOTH|\[[^\]]*\])/.exec(text)?.[1];
    if (!route || !screen || !editionsRaw) continue;
    const editions =
      editionsRaw === 'BOTH'
        ? ['hosted', 'local']
        : [...editionsRaw.matchAll(/'([^']+)'/g)].map((e) => e[1]);
    const kind = /kind:\s*'([^']+)'/.exec(text)?.[1] ?? 'page';
    entries.push({ route, screen, editions, kind });
  }
  return entries;
}

function entryFile(screen) {
  return `${BANNER}\nexport { ${screen} as default } from '@aflow/web-product/ui';\n`;
}

/** Every generated file currently on disk, so a removed route leaves no orphan. */
function existingGenerated(root) {
  const found = [];
  const walk = (dir) => {
    let items;
    try {
      items = readdirSync(dir, { withFileTypes: true });
    } catch {
      return;
    }
    for (const item of items) {
      const full = join(dir, item.name);
      if (item.isDirectory()) walk(full);
      else if (
        (item.name === 'page.tsx' || item.name === 'layout.tsx') &&
        readFileSync(full, 'utf8').startsWith(BANNER)
      )
        found.push(full);
    }
  };
  walk(root);
  return found;
}

const manifest = readManifest();
if (manifest.length === 0) {
  console.error('[web:routes] the manifest parsed to nothing — refusing to erase route trees');
  process.exit(1);
}

const problems = [];
let written = 0;

for (const [app, { dir: root, serves }] of Object.entries(APPS)) {
  // An application the edition cut removed has no tree to compare against, and
  // reporting its absence as a mismatch fails the check in the tree it is meant
  // to verify. Skipped rather than listed, so a public core checks the
  // application it actually ships.
  if (!existsSync(join(REPO, app))) continue;
  const wanted = new Map();
  for (const entry of manifest) {
    if (!entry.editions.some((edition) => serves.includes(edition))) continue;
    const path = join(root, entry.route, entry.kind === 'layout' ? 'layout.tsx' : 'page.tsx');
    if (wanted.has(path)) {
      problems.push(`${app}: two screens claim ${entry.route}`);
      continue;
    }
    wanted.set(path, entryFile(entry.screen));
  }

  for (const [path, contents] of wanted) {
    let current = null;
    try {
      current = readFileSync(path, 'utf8');
    } catch {
      /* absent */
    }
    if (current === contents) continue;
    if (CHECK) {
      problems.push(`${relative(REPO, path)} is ${current === null ? 'missing' : 'stale'}`);
      continue;
    }
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, contents);
    written += 1;
  }

  for (const path of existingGenerated(root)) {
    if (wanted.has(path)) continue;
    if (CHECK) problems.push(`${relative(REPO, path)} is no longer in the manifest`);
    else {
      rmSync(path);
      // A route directory with no entry file is not a route, but it is litter —
      // and a reader finding one cannot tell whether the route was dropped or
      // the generator half-finished.
      let dir = dirname(path);
      // `rmSync` without `recursive` refuses a directory outright, which threw
      // the first time a route was ever dropped from an app — after the orphan
      // file was gone and before the sweep finished.
      while (dir.startsWith(root) && dir !== root && readdirSync(dir).length === 0) {
        rmdirSync(dir);
        dir = dirname(dir);
      }
      written += 1;
    }
  }
}

if (problems.length > 0) {
  console.error('[web:routes] ' + (CHECK ? 'the route tree is out of date:' : 'refused:'));
  for (const p of problems) console.error('  - ' + p);
  console.error(CHECK ? '\nRun `yarn web:routes`.' : '');
  process.exit(1);
}

console.log(
  CHECK
    ? `[web:routes] ${manifest.length} routes match the tree`
    : `[web:routes] ${manifest.length} routes, ${written} file(s) changed`,
);
